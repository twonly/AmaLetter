export const SELF_HARM_KEYWORDS = [
  '不想活',
  '不想活了',
  '想死',
  '解脱',
  '再也不想',
  '跳下去',
  '跳楼',
  '安眠药',
  '割腕',
  '自杀',
  '结束自己',
  '一了百了',
  '消失算了',
];

export function detectSelfHarm(input: string): boolean {
  const normalized = input.replace(/\s+/g, '');
  return SELF_HARM_KEYWORDS.some((kw) => normalized.includes(kw));
}

